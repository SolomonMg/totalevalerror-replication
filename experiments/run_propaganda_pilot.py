# Item sampling
# ---------------------------------------------------------------------------
def load_human_data() -> pd.DataFrame:
    """Load and return the human RA data."""
    df = pd.read_csv(HUMAN_DATA_PATH)
    return df


def compute_item_disagreement(df: pd.DataFrame) -> pd.DataFrame:
    """Compute per-item human disagreement (SD of value_1_final across 9 RAs)."""
    disagreement = (
        df.groupby("question_ID")["value_1_final"]
        .agg(["mean", "std", "count"])
        .reset_index()
    )
    disagreement.columns = [
        "question_ID",
        "mean_favorability",
        "sd_favorability",
        "n_raters",
    ]
    # Merge item metadata (one row per question)
    item_meta = (
        df.groupby("question_ID")[
            [
                "question_english",
                "question_type",
                "question_focus",
                "english_question_output",
                "chinese_question_outputed_translated_english_final",
            ]
        ]
        .first()
        .reset_index()
    )
    disagreement = disagreement.merge(item_meta, on="question_ID")
    return disagreement


def sample_pilot_items(
    disagreement: pd.DataFrame, n_items: int, seed: int
) -> pd.DataFrame:
    """Stratified sample by disagreement level and question_type.

    Splits items into three disagreement bins (low/med/high) and samples
    proportionally, balancing across question_type within each bin.
    """
    rng = random.Random(seed)

    # Assign disagreement bin
    disagreement = disagreement.copy()
    conditions = [
        disagreement["sd_favorability"] < 0.2,
        (disagreement["sd_favorability"] >= 0.2)
        & (disagreement["sd_favorability"] <= 0.45),
        disagreement["sd_favorability"] > 0.45,
    ]
    labels = ["low", "medium", "high"]
    disagreement["disagree_bin"] = pd.cut(
        disagreement["sd_favorability"],
        bins=[-0.01, 0.2, 0.45, 1.0],
        labels=labels,
    )

    # Target counts per bin (roughly equal thirds)
    n_per_bin = {
        "low": 17 if n_items >= 50 else max(1, n_items // 3),
        "medium": 16 if n_items >= 50 else max(1, n_items // 3),
        "high": 17 if n_items >= 50 else max(1, n_items // 3),
    }
    # For small n_items (smoke), just do equal splits
    if n_items < 50:
        base = n_items // 3
        remainder = n_items - base * 3
        n_per_bin = {"low": base, "medium": base, "high": base}
        for i, k in enumerate(["low", "medium", "high"]):
            if i < remainder:
                n_per_bin[k] += 1

    sampled = []
    for bin_label in labels:
        bin_df = disagreement[disagreement["disagree_bin"] == bin_label]
        target_n = n_per_bin[bin_label]

        if len(bin_df) <= target_n:
            sampled.append(bin_df)
            continue

        # Balance across question_type within each bin
        qtypes = bin_df["question_type"].unique().tolist()
        rng.shuffle(qtypes)
        per_qtype = max(1, target_n // len(qtypes))
        remainder = target_n - per_qtype * len(qtypes)

        bin_sampled = []
        for j, qt in enumerate(qtypes):
            qt_df = bin_df[bin_df["question_type"] == qt]
            n_take = per_qtype + (1 if j < remainder else 0)
            n_take = min(n_take, len(qt_df))
            if n_take > 0:
                bin_sampled.append(qt_df.sample(n=n_take, random_state=seed))

        bin_result = pd.concat(bin_sampled)

        # If we still need more (some question_types had too few), fill from remainder
        if len(bin_result) < target_n:
            remaining = bin_df[~bin_df["question_ID"].isin(bin_result["question_ID"])]
            n_extra = target_n - len(bin_result)
            if len(remaining) >= n_extra:
                bin_result = pd.concat(
                    [bin_result, remaining.sample(n=n_extra, random_state=seed)]
                )

        sampled.append(bin_result)

    result = pd.concat(sampled).reset_index(drop=True)

    # Trim to exact target if slightly over
    if len(result) > n_items:
        result = result.sample(n=n_items, random_state=seed).reset_index(drop=True)

    return result


def get_or_create_pilot_items(n_items: int, seed: int) -> pd.DataFrame:
    """Load pilot items from cache, or sample and save them."""
    if PILOT_ITEMS_PATH.exists():
        items = pd.read_csv(PILOT_ITEMS_PATH)
        print(f"  Loaded {len(items)} cached pilot items from {PILOT_ITEMS_PATH}")
        # If cached items match requested n_items, use them; otherwise resample
        if len(items) == n_items:
            return items
        print(f"  Cached item count ({len(items)}) != requested ({n_items}); resampling")

    df = load_human_data()
    disagreement = compute_item_disagreement(df)
    items = sample_pilot_items(disagreement, n_items, seed)

    # Save
    PILOT_ITEMS_PATH.parent.mkdir(parents=True, exist_ok=True)
    items.to_csv(PILOT_ITEMS_PATH, index=False)
    print(f"  Saved {len(items)} pilot items to {PILOT_ITEMS_PATH}")

    return items


# ---------------------------------------------------------------------------
# Prompt construction
# ---------------------------------------------------------------------------
def build_prompt(
    variant_id: int,
    question: str,
    focus: str,
    response_cn: str,
    response_en: str,
    presentation_order: str,
) -> str:
    """Build a prompt from the template, with counterbalanced order.

    Args:
        variant_id: Index into PROMPT_VARIANTS (0-4).
        question: The English question text.
        focus: The question_focus (e.g., "China", "Xi Jinping").
        response_cn: Chinese-origin completion (translated to English).
        response_en: English-origin completion.
        presentation_order: "cn_first" or "en_first".

    Returns:
        Formatted prompt string.
    """
    template = PROMPT_VARIANTS[variant_id]
    if presentation_order == "cn_first":
        r1, r2 = response_cn, response_en
    else:
        r1, r2 = response_en, response_cn
    return template.format(
        question=question, focus=focus, response_1=r1, response_2=r2
    )


def parse_outcome(response_text: str, presentation_order: str) -> dict:
    """Parse LLM response into a standardized outcome.

    Returns:
        dict with:
            raw_choice: The number the LLM said (1 or 2), or None if unparseable
            cn_more_favorable: 1 if Chinese-origin was judged more favorable,
                               0 if English-origin, None if unparseable
    """
    if response_text is None:
        return {"raw_choice": None, "cn_more_favorable": None}

    text = response_text.strip()
    # Extract first digit that is 1 or 2
    raw_choice = None
    for ch in text:
        if ch in ("1", "2"):
            raw_choice = int(ch)
            break

    if raw_choice is None:
        return {"raw_choice": None, "cn_more_favorable": None}

    # Map to canonical direction: did the judge pick Chinese-origin?
    if presentation_order == "cn_first":
        cn_more_favorable = 1 if raw_choice == 1 else 0
    else:
        cn_more_favorable = 1 if raw_choice == 2 else 0

    return {"raw_choice": raw_choice, "cn_more_favorable": cn_more_favorable}


# ---------------------------------------------------------------------------
# Cost estimation
# ---------------------------------------------------------------------------
def estimate_cost(n_items, stage_cfg):
    """Estimate total API cost."""
    n_variants = stage_cfg["n_prompt_variants"]
    n_temps = len(stage_cfg["temperatures"])
    n_reps = stage_cfg["n_replications"]
    n_models = len(stage_cfg["models"])

    n_calls = n_items * n_variants * n_temps * n_reps * n_models
    # Each prompt: ~800 input tokens (question + two completions), ~5 output tokens
    avg_input_tokens = 800
    avg_output_tokens = 5

    total_cost = 0.0
    for model in stage_cfg["models"]:
        pricing = MODEL_PRICING.get(model, {"input": 5.0, "output": 15.0})
        model_calls = n_calls / n_models
        cost = (
            model_calls * avg_input_tokens * pricing["input"] / 1e6
            + model_calls * avg_output_tokens * pricing["output"] / 1e6
        )
        total_cost += cost

    return n_calls, total_cost


# ---------------------------------------------------------------------------
# Query with retry (follows run_demo.py pattern)
# ---------------------------------------------------------------------------
def query_with_retry(client, model, prompt, system_prompt, temperature, seed):
    """Query model with exponential backoff retry."""
    for attempt in range(MAX_RETRIES):
        try:
            return query_model(
                client=client,
                model=model,
                prompt=prompt,
                system_prompt=system_prompt,
                temperature=temperature,
                max_tokens=MAX_TOKENS,
                seed=seed,
            )
        except Exception as e:
            if attempt < MAX_RETRIES - 1:
                delay = RETRY_BASE_DELAY_S * (2**attempt)
                print(f"\n  Retry {attempt + 1}/{MAX_RETRIES} for {model}: {e}")
                time.sleep(delay)
            else:
                print(f"\n  Failed after {MAX_RETRIES} attempts: {e}")
                return {
                    "model": model,
                    "prompt": prompt,
                    "system_prompt": system_prompt,
                    "temperature": temperature,
                    "seed": seed,
                    "response": None,
                    "finish_reason": "error",
                    "elapsed_s": 0,
                    "usage": {"prompt_tokens": 0, "completion_tokens": 0},
                    "error": str(e),
                }


# ---------------------------------------------------------------------------
# Main run loop
# ---------------------------------------------------------------------------
def run_propaganda(stage: str, dry_run: bool = False):
    """Run the propaganda favorability judgment experiment."""
    stage_cfg = PROPAGANDA_STAGES[stage]
    n_items_target = stage_cfg["n_items"]

    print(f"=== Propaganda Pilot: {stage} ===")
    print(f"Description: {stage_cfg['description']}")

    # Step 1: Get items
    items = get_or_create_pilot_items(n_items_target, SEED)
    n_items = len(items)

    # Print sampling summary
    if "disagree_bin" in items.columns:
        print(f"\n  Disagreement strata:")
        for bin_label in ["low", "medium", "high"]:
            n_bin = (items["disagree_bin"] == bin_label).sum()
            print(f"    {bin_label}: {n_bin} items")
        print(f"  Question types:")
        for qt in sorted(items["question_type"].unique()):
            n_qt = (items["question_type"] == qt).sum()
            print(f"    {qt}: {n_qt} items")

    # Step 2: Build full factorial
    n_calls, est_cost = estimate_cost(n_items, stage_cfg)
    print(f"\n  Design:")
    print(f"    Items: {n_items}")
    print(f"    Prompt variants: {stage_cfg['n_prompt_variants']}")
    print(f"    Judge models: {stage_cfg['models']}")
    print(f"    Temperatures: {stage_cfg['temperatures']}")
    print(f"    Replications: {stage_cfg['n_replications']}")
    print(f"    Total API calls: {n_calls:,}")
    print(f"    Estimated cost: ${est_cost:.2f}")

    if dry_run:
        print("\n  [DRY RUN] Exiting without making API calls.")
        # Print a sample prompt
        row = items.iloc[0]
        sample_prompt = build_prompt(
            variant_id=0,
            question=row["question_english"],
            focus=row["question_focus"],
            response_cn=row["chinese_question_outputed_translated_english_final"],
            response_en=row["english_question_output"],
            presentation_order="cn_first",
        )
        print(f"\n  Sample prompt (variant 0, cn_first):\n")
        print("  " + sample_prompt.replace("\n", "\n  "))
        return

    # Step 3: Build all combinations
    rng = random.Random(SEED)
    combos = []
    for _, item_row in items.iterrows():
        for variant_id in range(stage_cfg["n_prompt_variants"]):
            for model in stage_cfg["models"]:
                for temp in stage_cfg["temperatures"]:
                    for rep in range(stage_cfg["n_replications"]):
                        # Counterbalance: each (item, variant, model, temp, rep) gets
                        # a deterministic but pseudo-random presentation order
                        combo_seed = hash(
                            (item_row["question_ID"], variant_id, model, temp, rep)
                        )
                        order = "cn_first" if (combo_seed % 2 == 0) else "en_first"
                        combos.append(
                            {
                                "question_ID": item_row["question_ID"],
                                "question_english": item_row["question_english"],
                                "question_focus": item_row["question_focus"],
                                "question_type": item_row["question_type"],
                                "response_cn": item_row[
                                    "chinese_question_outputed_translated_english_final"
                                ],
                                "response_en": item_row["english_question_output"],
                                "variant_id": variant_id,
                                "model": model,
                                "temperature": temp,
                                "replication": rep,
                                "presentation_order": order,
                            }
                        )

    # Shuffle to spread models/items across time (better for rate limiting)
    rng.shuffle(combos)

    # Step 4: Resume support — load already-completed combos
    OUTPATH.parent.mkdir(parents=True, exist_ok=True)
    combos_done = set()
    if OUTPATH.exists():
        with open(OUTPATH) as f:
            for line in f:
                r = json.loads(line)
                combos_done.add(
                    (
                        r["question_ID"],
                        str(r["variant_id"]),
                        r["judge_model"],
                        str(r["temperature"]),
                        str(r["replication"]),
                    )
                )
        print(f"\n  Resuming: {len(combos_done)} calls already completed")

    combos_remaining = [
        c
        for c in combos
        if (
            c["question_ID"],
            str(c["variant_id"]),
            c["model"],
            str(c["temperature"]),
            str(c["replication"]),
        )
        not in combos_done
    ]
    print(f"  Remaining calls: {len(combos_remaining)}")

    if not combos_remaining:
        print("  Nothing to do — all calls already completed.")
        return

    # Step 5: Run queries
    client = get_client()
    total_input_tokens = 0
    total_output_tokens = 0
    results_buffer = []

    for combo in tqdm(combos_remaining, desc=f"Propaganda {stage}"):
        prompt = build_prompt(
            variant_id=combo["variant_id"],
            question=combo["question_english"],
            focus=combo["question_focus"],
            response_cn=combo["response_cn"],
            response_en=combo["response_en"],
            presentation_order=combo["presentation_order"],
        )

        rep_seed = SEED + combo["replication"]
        result = query_with_retry(
            client=client,
            model=combo["model"],
            prompt=prompt,
            system_prompt=SYSTEM_PROMPT,
            temperature=combo["temperature"],
            seed=rep_seed if combo["temperature"] == 0.0 else None,
        )

        # Parse the outcome
        outcome = parse_outcome(
            result.get("response"), combo["presentation_order"]
        )

        # Build output record
        record = {
            "question_ID": combo["question_ID"],
            "question_type": combo["question_type"],
            "question_focus": combo["question_focus"],
            "variant_id": combo["variant_id"],
            "judge_model": combo["model"],
            "temperature": combo["temperature"],
            "replication": combo["replication"],
            "presentation_order": combo["presentation_order"],
            "raw_choice": outcome["raw_choice"],
            "cn_more_favorable": outcome["cn_more_favorable"],
            "response_raw": result.get("response"),
            "finish_reason": result.get("finish_reason"),
            "elapsed_s": result.get("elapsed_s", 0),
            "usage": result.get("usage", {}),
            "timestamp": datetime.now(tz=timezone.utc).isoformat(),
            "error": result.get("error"),
        }

        if result.get("usage"):
            total_input_tokens += result["usage"].get("prompt_tokens", 0)
            total_output_tokens += result["usage"].get("completion_tokens", 0)

        results_buffer.append(record)

        # Flush every 50 records
        if len(results_buffer) >= 50:
            save_results(results_buffer, OUTPATH)
            results_buffer = []

        time.sleep(REQUEST_DELAY_S)

    # Flush remaining
    if results_buffer:
        save_results(results_buffer, OUTPATH)

    # Compute actual cost
    actual_cost = 0.0
    for model in stage_cfg["models"]:
        pricing = MODEL_PRICING.get(model, {"input": 5.0, "output": 15.0})
        model_frac = 1.0 / len(stage_cfg["models"])
        actual_cost += (
            total_input_tokens * model_frac * pricing["input"] / 1e6
            + total_output_tokens * model_frac * pricing["output"] / 1e6
        )

    print(f"\n=== Done ===")
    print(f"  Results saved to: {OUTPATH}")
    print(f"  New calls this run: {len(combos_remaining)}")
    print(f"  Resumed from checkpoint: {len(combos_done)}")
    print(
        f"  Total tokens: {total_input_tokens:,} input, "
        f"{total_output_tokens:,} output"
    )
    print(f"  Actual cost: ~${actual_cost:.2f}")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(
        description="Collect LLM judge favorability ratings on propaganda_llm items"
    )
    parser.add_argument(
        "--stage",
        required=True,
        choices=PROPAGANDA_STAGES.keys(),
        help="Experiment stage: smoke (5 items, minimal) or pilot (50 items, full factorial)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print design and cost estimate without making API calls",
    )
    args = parser.parse_args()

    run_propaganda(args.stage, dry_run=args.dry_run)


if __name__ == "__main__":
    main()
