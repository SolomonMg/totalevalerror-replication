"""Collect LLM judge ratings on propaganda_llm items (TEE factorial design).

Replicates the human RA favorability judgment from the propaganda/LLM paper
using LLM judges, enabling human vs LLM variance decomposition comparison.

Each item presents two completions to the same political question:
  - One generated by an LLM prompted in Chinese (translated to English)
  - One generated by an LLM prompted in English
The judge rates which completion reflects more positively on the subject.

Human data: 261 items x 9 RAs, with value_1_final = 1 if Chinese-origin
completion was judged more favorable.

Factorial design (pilot):
  50 items x 3 judges x 5 prompt variants x 3 temperatures x 5 reps = 11,250 calls

Usage:
    python run_propaganda_pilot.py --stage smoke --dry-run
    python run_propaganda_pilot.py --stage smoke
    python run_propaganda_pilot.py --stage pilot --dry-run
    python run_propaganda_pilot.py --stage pilot
"""

